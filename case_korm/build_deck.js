/* Питч-дек «Корм для людей» для инвесторов.
   Запуск: node case_korm/build_deck.js
   Все утверждения согласованы с брифом: подтверждённых характеристик,
   цен, сроков и партнёров не приводим; цифры помечены как гипотезы. */
const pptxgen = require("pptxgenjs");
const path = require("path");

const DIR = __dirname;
const IMG = (n) => path.join(DIR, "deck_img", n + ".jpg");

const INK = "151515";
const PAPER = "F6F3EB";
const PAPER2 = "EBE5D4";
const YELLOW = "FFD600";
const OLIVE = "526333";
const ORANGE = "DE702D";
const MUTED = "6E695C";
const LINE = "DCD4C0";
const WHITE = "FFFFFF";
const CREAM = "E8E4D6";

const HEAD = "Arial";
const BODY = "Calibri";
const W = 13.3, H = 7.5, M = 0.62;

const pres = new pptxgen();
pres.layout = "LAYOUT_WIDE";
pres.author = "Корм для людей";
pres.title = "Корм для людей — питч для инвестора";

let n = 0;

function slide(bg) {
  const s = pres.addSlide();
  s.background = { color: bg || PAPER };
  n += 1;
  return s;
}

function foot(s, dark) {
  s.addText("Корм для людей · проект на стадии концепции · числовые ориентиры — рабочие гипотезы", {
    x: M, y: H - 0.46, w: 9.5, h: 0.3, isTextBox: true, margin: 0,
    fontFace: BODY, fontSize: 9, color: dark ? "7C7768" : MUTED,
  });
  s.addText(String(n), {
    x: W - M - 0.6, y: H - 0.46, w: 0.6, h: 0.3, isTextBox: true, margin: 0,
    fontFace: BODY, fontSize: 9, color: dark ? "7C7768" : MUTED, align: "right",
  });
}

function title(s, text, opts) {
  const o = opts || {};
  s.addText(text, {
    x: o.x || M, y: o.y || 0.5, w: o.w || 8.6, h: o.h || 1.1, isTextBox: true, margin: 0,
    fontFace: HEAD, fontSize: o.size || 34, bold: true, color: o.color || INK,
    charSpacing: -0.4, lineSpacing: o.size ? o.size * 1.12 : 38, valign: "top",
  });
}

function eyebrow(s, text, x, y, color) {
  s.addText(text, {
    x: x, y: y, w: 6, h: 0.26, isTextBox: true, margin: 0,
    fontFace: BODY, fontSize: 10.5, bold: true, color: color || ORANGE, charSpacing: 1.6,
  });
}

function card(s, x, y, w, h, fill, border) {
  s.addShape(pres.ShapeType.roundRect, {
    x: x, y: y, w: w, h: h, rectRadius: 0.16,
    fill: { color: fill || PAPER2 },
    line: border === false ? { type: "none" } : { color: LINE, width: 1 },
  });
}

function body(s, text, x, y, w, h, opts) {
  const o = opts || {};
  s.addText(text, {
    x: x, y: y, w: w, h: h, isTextBox: true, margin: 0,
    fontFace: BODY, fontSize: o.size || 13, color: o.color || INK,
    lineSpacing: o.line || (o.size ? o.size * 1.35 : 18), valign: o.valign || "top",
    bold: o.bold || false, align: o.align || "left",
  });
}

function bullets(s, items, x, y, w, h, opts) {
  const o = opts || {};
  s.addText(items.map((t, i) => ({
    text: t, options: { bullet: true, breakLine: i < items.length - 1 },
  })), {
    x: x, y: y, w: w, h: h, isTextBox: true, margin: 0,
    fontFace: BODY, fontSize: o.size || 12.5, color: o.color || INK, valign: "top",
    lineSpacing: o.line || 17, paraSpaceAfter: o.gap === undefined ? 6 : o.gap,
  });
}

function photo(s, name, x, y, size) {
  s.addShape(pres.ShapeType.roundRect, {
    x: x - 0.07, y: y - 0.07, w: size + 0.14, h: size + 0.14, rectRadius: 0.18,
    fill: { color: WHITE }, line: { color: LINE, width: 1 },
  });
  s.addImage({ path: IMG(name), x: x, y: y, w: size, h: size });
}

