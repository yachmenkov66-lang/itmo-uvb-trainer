ROW = {t[0]: t[1] for t in PARAMS if t[0]}
INPUT_ROWS = {t[1] for t in PARAMS
              if t[3] is not None and not (isinstance(t[3], str) and t[3].startswith("="))}

P = "Параметры"


def p(key):
    """Абсолютная ссылка на параметр по ключу."""
    return f"{P}!$B${ROW[key]}"


def build_params(wb):
    ws = wb.create_sheet(P)
    for col, w in (("A", 50), ("B", 15), ("C", 42), ("D", 15), ("E", 15), ("F", 15)):
        ws.column_dimensions[col].width = w
    head = Font(bold=True, color="FFFFFF")
    head_fill = PatternFill("solid", fgColor="1F4E79")
    sect = Font(bold=True, color="1F4E79")
    sect_fill = PatternFill("solid", fgColor="DDEBF7")
    inp_fill = PatternFill("solid", fgColor="FFF2CC")
    calc_fill = PatternFill("solid", fgColor="E2EFDA")
    thin = Side(style="thin", color="BFBFBF")
    border = Border(thin, thin, thin, thin)

    def style_input(cell, fmt):
        cell.number_format = fmt or "General"
        cell.alignment = Alignment(horizontal="right")
        cell.border = border
        cell.fill = inp_fill

    for key, row, label, value, fmt, note, scen in PARAMS:
        ws.cell(row, 1, label)
        if note:
            ws.cell(row, 3, note).font = Font(italic=True, color="808080")

        if row == 1:
            for c in range(1, 7):
                ws.cell(row, c).font = head
                ws.cell(row, c).fill = head_fill
            continue
        if row == 2:
            ws.cell(row, 1).font = Font(italic=True, color="C00000")
            continue
        if value is None and scen is None:          # заголовок раздела
            for c in range(1, 7):
                ws.cell(row, c).font = sect
                ws.cell(row, c).fill = sect_fill
            continue

        if scen:            # значение выбирает переключатель сценария
            cell = ws.cell(row, 2, f"=CHOOSE($B$11,D{row},E{row},F{row})")
            cell.number_format = fmt or "General"
            cell.font = Font(bold=True)
            cell.fill = calc_fill
            cell.border = border
            for i, v in enumerate(scen):
                style_input(ws.cell(row, 4 + i, v), fmt)
            continue

        cell = ws.cell(row, 2, value)
        style_input(cell, fmt)
        if isinstance(value, str) and value.startswith("="):
            cell.fill = calc_fill
            cell.font = Font(bold=True)

    # строка 11 — одновременно заголовок раздела и переключатель сценария
    for c in range(1, 7):
        ws.cell(11, c).font = sect
        ws.cell(11, c).fill = sect_fill
        ws.cell(11, c).border = border
    ws["B11"].fill = inp_fill
    ws["B11"].font = Font(bold=True, size=12, color="C00000")
    ws["B11"].alignment = Alignment(horizontal="center")
    for i, name in enumerate(("1 — пессимистичный", "2 — базовый", "3 — оптимистичный")):
        c = ws.cell(11, 4 + i, name)
        c.font = Font(bold=True, color="1F4E79")
        c.alignment = Alignment(horizontal="center")
    ws.freeze_panes = "A4"
    return ws


# ------------------------------------------------------------------- ДДС
# служебные строки: 48 — № месяца, 49 — обязательство перед инвестором,
# 50 — себестоимость, 51/52 — валовая прибыль и маржа, 53/54 — операционный
# поток и накопленный, 55 — поток инвестора, 56-58 — флаги дат,
# 59 — инвестиции накопленным итогом, 60 — флаг месяца транша
def m(col):
    return f"{col}$48"


def hired(col, month_key, body):
    """Расход появляется начиная с месяца, заданного параметром."""
    return f"IF({m(col)}<{p(month_key)},0,{body})"


def salary(col, zp_key):
    return f"ROUND({p(zp_key)}*IF({m(col)}<=12,1,1+{p('индексация')}),0)"


def revenue(col):
    return f"({col}3+{col}6+{col}9)"


def b2c(col):
    return f"({col}3+{col}6)"


def opex_no_tax(col):
    """Операционные расходы без строки «Налоги прочее» — база для УСН."""
    return f"({col}17+{col}18+{col}19+{col}21+{col}26+{col}34+{col}38+{col}42)"


def opex_all(col):
    """Все операционные расходы, без возврата инвестору."""
    return f"({col}17+{col}22+{col}26+{col}34+{col}38+{col}42)"


def fill_dds(ws):
    prev = None
    for c in COLS:
        first = prev is None
        cash_in = p("сальдо0") if first else f"{prev}46"

        ws[f"{c}48"] = "=1" if first else f"={prev}48+1"

        # ---------- ПРИХОД
        ws[f"{c}4"] = (f"={p('кол1')}" if first else
                       f"=ROUND({prev}4*(1+IF({m(c)}<=12,{p('рост1_1')},{p('рост1_2')})),0)")
        ws[f"{c}5"] = f"={p('цена1')}"
        ws[f"{c}7"] = (f"=IF({m(c)}<{p('старт2')},0,{p('кол2')})" if first else
                       f"=IF({m(c)}<{p('старт2')},0,IF({prev}7=0,{p('кол2')},"
                       f"ROUND({prev}7*(1+IF({m(c)}<=12,{p('рост2_1')},{p('рост2_2')})),0)))")
        ws[f"{c}8"] = f"={p('цена2')}"
        ws[f"{c}9"] = (f"=IF({m(c)}<{p('старт3')},0,ROUND({p('кол3')}*{p('цена3')},0))" if first else
                       f"=IF({m(c)}<{p('старт3')},0,IF({prev}9=0,ROUND({p('кол3')}*{p('цена3')},0),"
                       f"ROUND({prev}9*(1+{p('рост3')}),0)))")

        # ИНВЕСТИЦИИ: доливаем ровно столько, сколько не хватает до целевого
        # остатка, кратно шагу; в 1-м месяце — не меньше стартового транша;
        # суммарно — не больше лимита инвестора
        # в 1-м месяце берём ровно стартовый транш (если его хватает закрыть
        # месяц), целевой остаток добираем со 2-го месяца
        target = "0" if first else p("остаток_цель")
        need = f"({target}-({cash_in}+{revenue(c)}-{opex_all(c)}-{c}43))"
        step = f"ROUNDUP({need}/{p('шаг')},0)*{p('шаг')}"
        room = p("лимит") if first else f"MAX(0,{p('лимит')}-{prev}59)"
        ws[f"{c}10"] = (f"=MIN(MAX({p('транш1')},{step}),{room})" if first else
                        f"=MIN(MAX(0,{step}),{room})")

        # ---------- РАСХОД: IT-блок (здесь же оклады разработчика и дизайнера)
        ws[f"{c}13"] = "=" + hired(c, "разраб_мес", salary(c, "разраб_зп"))
        ws[f"{c}14"] = "=" + hired(c, "дизайн_мес", salary(c, "дизайн_зп"))
        ws[f"{c}15"] = f"={p('хостинг')}"
        ws[f"{c}16"] = f"={p('сервер')}"

        # бухгалтерия и налоги
        ws[f"{c}18"] = f"={p('бухгалтерия')}"
        ws[f"{c}19"] = f"=ROUND(({c}34+{c}13+{c}14)*{p('взносы')},0)"
        ws[f"{c}20"] = (f"=ROUND(MAX({p('усн')}*({revenue(c)}-{opex_no_tax(c)}),"
                        f"{p('усн_мин')}*{revenue(c)}),0)")
        ws[f"{c}21"] = f"=ROUND({b2c(c)}*{p('эквайринг')},0)"

        # реклама
        ws[f"{c}23"] = f"=ROUND(MAX({p('рек_мин')},{revenue(c)}*{p('рек_пц')}),0)"
        ws[f"{c}24"] = "=" + hired(c, "офл_мес", p("офл_рек"))
        ws[f"{c}25"] = "=" + hired(c, "seo_мес", p("seo"))

        # ФОТ
        ws[f"{c}27"] = "=" + hired(c, "прод1_мес", f"ROUND({revenue(c)}*{p('прод1_пц')},0)")
        ws[f"{c}28"] = "=" + hired(c, "прод2_мес", f"ROUND({revenue(c)}*{p('прод2_пц')},0)")
        ws[f"{c}29"] = "=" + hired(c, "маркет_мес", f"ROUND({revenue(c)}*{p('маркет_пц')},0)")
        ws[f"{c}30"] = "=" + hired(c, "прод1_мес", salary(c, "прод1_зп"))
        ws[f"{c}31"] = "=" + hired(c, "прод2_мес", salary(c, "прод2_зп"))
        ws[f"{c}32"] = "=" + hired(c, "маркет_мес", salary(c, "маркет_зп"))
        ws[f"{c}33"] = "=" + hired(c, "ceo_мес", salary(c, "ceo_зп"))

