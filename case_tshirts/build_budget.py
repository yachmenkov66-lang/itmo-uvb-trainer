# индекс месяца лежит в строке 48 (B48=1 ... Y48=24)
def m(col):
    return f"{col}$48"


def year2(col, base):
    """Оклад с индексацией со 2-го года."""
    return f"ROUND({base}*IF({m(col)}<=12,1,1+{p(34)}),0)"


def revenue(col):
    return f"({col}3+{col}6+{col}9)"


def b2c(col):
    return f"({col}3+{col}6)"


def opex_no_tax(col):
    """Операционные расходы без строки «Налоги прочее» (для расчёта УСН)."""
    return (f"({col}17+{col}18+{col}19+{col}21+{col}26+{col}34+{col}38+{col}42)")


def opex_all(col):
    """Все операционные расходы (без возврата инвестиций)."""
    return f"({col}17+{col}22+{col}26+{col}34+{col}38+{col}42)"


def fill_dds(ws):
    prev = None
    for col in COLS:
        c = col
        first = prev is None

        # --- служебная строка: номер месяца
        ws[f"{c}48"] = "=1" if first else f"={prev}48+1"

        # --- ПРИХОД
        # товар 1: количество и цена
        ws[f"{c}4"] = f"={p(12)}" if first else \
            f"=ROUND({prev}4*(1+IF({m(c)}<=12,{p(13)},{p(14)})),0)"
        ws[f"{c}5"] = f"={p(4)}"
        # товар 2: старт с месяца-параметра, затем рост
        ws[f"{c}7"] = (f"=IF({m(c)}<{p(15)},0,{p(16)})" if first else
                       f"=IF({m(c)}<{p(15)},0,IF({prev}7=0,{p(16)},"
                       f"ROUND({prev}7*(1+IF({m(c)}<=12,{p(17)},{p(18)})),0)))")
        ws[f"{c}8"] = f"={p(6)}"
        # товар 3 (B2B) — сразу в рублях
        ws[f"{c}9"] = (f"=IF({m(c)}<{p(19)},0,ROUND({p(20)}*{p(8)},0))" if first else
                       f"=IF({m(c)}<{p(19)},0,IF({prev}9=0,ROUND({p(20)}*{p(8)},0),"
                       f"ROUND({prev}9*(1+{p(21)}),0)))")
        # инвестиции: два транша, размер считается от пиковой потребности (B62)
        ws[f"{c}10"] = (f"=IF({m(c)}=1,ROUNDUP($B$62*{p(63)}/100000,0)*100000,"
                        f"IF({m(c)}={p(64)},ROUNDUP($B$62*(1-{p(63)})/100000,0)*100000,0))")

        # --- РАСХОД: IT + 2 сотрудника в штате
        ws[f"{c}13"] = "=" + year2(c, p(32))
        ws[f"{c}14"] = "=" + year2(c, p(33))
        ws[f"{c}15"] = f"={p(46)}"
        ws[f"{c}16"] = f"={p(47)}"

        # --- бухгалтерия и налоги
        ws[f"{c}18"] = f"={p(48)}"
        ws[f"{c}19"] = f"=ROUND(({c}34+{c}13+{c}14)*{p(35)},0)"
        ws[f"{c}20"] = (f"=ROUND(MAX({p(58)}*({revenue(c)}-{opex_no_tax(c)}),"
                        f"{p(59)}*{revenue(c)}),0)")
        ws[f"{c}21"] = f"=ROUND({b2c(c)}*{p(49)},0)"

        # --- реклама
        ws[f"{c}23"] = f"=ROUND(MAX({p(39)},{revenue(c)}*{p(38)}),0)"
        ws[f"{c}24"] = f"=IF({m(c)}<{p(41)},0,{p(40)})"
        ws[f"{c}25"] = f"=IF({m(c)}<{p(43)},0,{p(42)})"

        # --- ФОТ (4 человека: 2 продажника, маркетолог, руководитель)
        ws[f"{c}27"] = f"=ROUND({revenue(c)}*{p(26)},0)"
        ws[f"{c}28"] = f"=IF({m(c)}<{p(29)},0,ROUND({revenue(c)}*{p(28)},0))"
        ws[f"{c}29"] = f"=ROUND({revenue(c)}*{p(31)},0)"
        ws[f"{c}30"] = "=" + year2(c, p(25))
        ws[f"{c}31"] = f"=IF({m(c)}<{p(29)},0," + year2(c, p(27)) + ")"
        ws[f"{c}32"] = "=" + year2(c, p(30))
        ws[f"{c}33"] = "=" + year2(c, p(24))

        # --- административные
        ws[f"{c}35"] = f"={p(50)}"
        ws[f"{c}36"] = f"={p(51)}"
        ws[f"{c}37"] = f"={p(52)}"

        # --- себестоимость, логистика, упаковка
        nxt = get_column_letter(ws[f"{c}1"].column + 1)
        stock = f"+IF({p(55)}=1,{nxt}50,0)" if first else ""
        ws[f"{c}39"] = f"={c}50{stock}"
        ws[f"{c}40"] = f"=ROUND({revenue(c)}*{p(53)},0)"
        ws[f"{c}41"] = f"=ROUND({b2c(c)}*{p(54)},0)"

        # --- возврат инвестиций: из операционного потока, в пределах остатка
        #     обязательства и свободных денег сверх подушки
        cash_in = f"{p(70)}" if first else f"{prev}46"
        ws[f"{c}43"] = (f"=MIN({c}49,ROUND(MAX(0,{c}53)*{p(66)},0),"
                        f"MAX(0,{cash_in}+{c}11-{opex_all(c)}-{p(67)}))")

        # --- служебные строки расчёта
        ws[f"{c}49"] = (f"=ROUND({c}10*{p(65)},0)" if first else
                        f"={prev}49-{prev}43+ROUND({c}10*{p(65)},0)")
        ws[f"{c}50"] = f"=ROUND({c}4*{p(5)}+{c}7*{p(7)}+{c}9*{p(9)},0)"
        ws[f"{c}51"] = f"={revenue(c)}-{c}50"
        ws[f"{c}52"] = f"=IF({revenue(c)}=0,0,{c}51/{revenue(c)})"
        ws[f"{c}53"] = f"={revenue(c)}-{opex_all(c)}"
        ws[f"{c}54"] = f"={c}53" if first else f"={prev}54+{c}53"
        ws[f"{c}55"] = f"={c}43-{c}10"
        ws[f"{c}56"] = f"=IF({c}53>0,{m(c)},9999)"
        ws[f"{c}57"] = f"=IF({c}54>0,{m(c)},9999)"
        ws[f"{c}58"] = f"=IF(AND({c}49>0,{c}49-{c}43<=0.5),{m(c)},9999)"

        prev = c

    # сальдо на начало периода — тоже формулой
    ws["B47"] = f"={p(70)}"
    # «осталось вернуть» = обязательство минус выплаченное
    ws["AA43"] = f"=ROUND($Z$10*{p(65)},0)-$Z$43"
    # итоги по строке для новых служебных строк
    for r in (50, 51, 53, 55):
        ws[f"Z{r}"] = f"=SUM(B{r}:Y{r})"
    ws["Z52"] = "=IF((Z3+Z6+Z9)=0,0,Z51/(Z3+Z6+Z9))"


