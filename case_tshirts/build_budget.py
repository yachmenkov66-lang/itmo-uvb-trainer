def build_params(wb):
    ws = wb.create_sheet(P)
    for col, w in (("A", 52), ("B", 15), ("C", 40), ("D", 15), ("E", 15), ("F", 15)):
        ws.column_dimensions[col].width = w
    head = Font(bold=True, color="FFFFFF")
    head_fill = PatternFill("solid", fgColor="1F4E79")
    sect = Font(bold=True, color="1F4E79")
    sect_fill = PatternFill("solid", fgColor="DDEBF7")
    inp_fill = PatternFill("solid", fgColor="FFF2CC")
    calc_fill = PatternFill("solid", fgColor="E2EFDA")
    thin = Side(style="thin", color="BFBFBF")
    border = Border(thin, thin, thin, thin)

    def style_input(cell, fmt):
        cell.number_format = fmt or "General"
        cell.alignment = Alignment(horizontal="right")
        cell.border = border
        cell.fill = inp_fill

    for row, label, value, fmt, note, scen in PARAMS:
        ws.cell(row, 1, label)
        if note:
            ws.cell(row, 3, note).font = Font(italic=True, color="808080")

        if row == 1:
            for c in range(1, 7):
                ws.cell(row, c).font = head
                ws.cell(row, c).fill = head_fill
        elif row == 2:
            ws.cell(row, 1).font = Font(italic=True, color="C00000")
        elif value is None and scen is None:
            for c in range(1, 7):
                ws.cell(row, c).font = sect
                ws.cell(row, c).fill = sect_fill
            continue

        if scen:  # значение выбирается переключателем сценария
            cell = ws.cell(row, 2, f"=CHOOSE($B$11,D{row},E{row},F{row})")
            cell.number_format = fmt or "General"
            cell.font = Font(bold=True)
            cell.fill = calc_fill
            cell.border = border
            for i, v in enumerate(scen):
                style_input(ws.cell(row, 4 + i, v), fmt)
            continue

        if value is None:
            continue
        cell = ws.cell(row, 2, value)
        style_input(cell, fmt)
        if not isinstance(value, str) or not value.startswith("="):
            pass
        else:
            cell.fill = calc_fill
            cell.font = Font(bold=True)

    # шапка блока сценариев
    ws["B11"].fill = inp_fill
    ws["B11"].font = Font(bold=True, size=12, color="C00000")
    for i, name in enumerate(("1 — пессимистичный", "2 — базовый", "3 — оптимистичный")):
        c = ws.cell(11, 4 + i, name)
        c.font = Font(bold=True, color="1F4E79")
        c.alignment = Alignment(horizontal="center")
        c.fill = sect_fill
    for c in range(1, 7):
        ws.cell(11, c).border = border
    ws.freeze_panes = "A4"
    return ws


