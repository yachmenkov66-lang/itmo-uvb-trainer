def build_pitch(wb):
    ws = wb.create_sheet("Питч")
    ws.column_dimensions["A"].width = 44
    ws.column_dimensions["B"].width = 18
    ws.column_dimensions["C"].width = 84
    head_fill = PatternFill("solid", fgColor="1F4E79")
    sect_fill = PatternFill("solid", fgColor="DDEBF7")
    pct_rows = {"Маржа «Базовая»", "Маржа «Pro / кастом»", "Маржа B2B-заказа",
                "Средняя валовая маржа проекта", "ROI инвестора за 24 мес.",
                "IRR инвестора, % годовых", "IRR проекта, % годовых",
                "Рентабельность по операционному потоку"}
    plain_rows = {"Месяц выхода в операционный плюс", "Месяц окупаемости проекта",
                  "Месяц полного возврата инвестору", "Проверка достаточности денег",
                  "Сценарий модели (1 песс. / 2 базовый / 3 опт.)"}

    for i, (label, formula, note) in enumerate(PITCH, start=1):
        ws.cell(i, 1, label)
        if note and formula is None and label and not label.isupper():
            ws.cell(i, 3, note).alignment = Alignment(wrap_text=True, vertical="top")
            ws.cell(i, 1).font = Font(bold=True)
        elif note:
            ws.cell(i, 3, note).font = Font(italic=True, color="808080")
        if formula is not None:
            cell = ws.cell(i, 2, formula)
            cell.font = Font(bold=True, color="1F4E79")
            if label in pct_rows:
                cell.number_format = PCT
            elif label in plain_rows:
                cell.number_format = "0"
            else:
                cell.number_format = MONEY
        if i == 1:
            for c in range(1, 4):
                ws.cell(i, c).font = Font(bold=True, size=14, color="FFFFFF")
                ws.cell(i, c).fill = head_fill
        elif label and label == label.upper() and label.strip():
            for c in range(1, 4):
                ws.cell(i, c).font = Font(bold=True, color="1F4E79")
                ws.cell(i, c).fill = sect_fill
        ws.row_dimensions[i].height = 30 if (note and formula is None) else None
    return ws


