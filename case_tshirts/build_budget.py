def decorate_dds(ws):
    for ref, text in DDS_LABELS.items():
        ws[ref] = text

    grey = Font(italic=True, color="808080", size=9)
    sect = Font(bold=True, color="1F4E79")
    sect_fill = PatternFill("solid", fgColor="DDEBF7")

    for row, label, fmt in SERVICE_ROWS:
        ws.cell(row, 1, label).font = grey
        for col in COLS + ["Z"]:
            cell = ws[f"{col}{row}"]
            if cell.value is not None:
                cell.number_format = fmt
                cell.font = grey

    for row, label, formula, fmt, note in KPI:
        ws.cell(row, 1, label)
        if formula is None:
            for c in range(1, 4):
                ws.cell(row, c).font = sect
                ws.cell(row, c).fill = sect_fill
            continue
        cell = ws.cell(row, 2, formula)
        if fmt:
            cell.number_format = fmt
        cell.font = Font(bold=True)
        cell.fill = PatternFill("solid", fgColor="E2EFDA")
        if note:
            ws.cell(row, 3, note).font = grey

    # форматы заполненных строк ДДС
    money_rows = [3, 5, 6, 8, 9, 10, 13, 14, 15, 16, 18, 19, 20, 21, 23, 24, 25,
                  27, 28, 29, 30, 31, 32, 33, 35, 36, 37, 39, 40, 41, 43, 47]
    for row in money_rows:
        for col in COLS + ["Z"]:
            cell = ws[f"{col}{row}"]
            if cell.value is not None:
                cell.number_format = MONEY
    for row in (4, 7):
        for col in COLS + ["Z"]:
            if ws[f"{col}{row}"].value is not None:
                ws[f"{col}{row}"].number_format = QTY
    ws.column_dimensions["A"].width = 46
    ws.column_dimensions["AA"].width = 16
    ws.freeze_panes = "B2"


